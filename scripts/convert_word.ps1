param (
    [Parameter(Mandatory=$true)]
    [string]$inputPath,
    [Parameter(Mandatory=$true)]
    [string]$outputPath
)

$ErrorActionPreference = "Stop"
$word = $null
$doc = $null

try {
    $fullInput = [System.IO.Path]::GetFullPath($inputPath)
    $fullOutput = [System.IO.Path]::GetFullPath($outputPath)

    if (-not (Test-Path $fullInput)) {
        throw "Input file not found: $fullInput"
    }

    $word = New-Object -ComObject Word.Application
    $word.Visible = $false
    $word.DisplayAlerts = 0

    # Open document (ConfirmConversions=$false, ReadOnly=$true, AddToRecentFiles=$false)
    $doc = $word.Documents.Open($fullInput, $false, $true, $false)

    # ExportAsFixedFormat parameters:
    # 1. OutputFileName: $fullOutput
    # 2. ExportFormat: 17 (wdExportFormatPDF)
    # 3. OpenAfterExport: $false
    # 4. OptimizeFor: 0 (wdExportOptimizeForPrint - MAXIMUM PRINT RESOLUTION, NO IMAGE DOWNSAMPLING)
    # 5. Range: 0 (wdExportAllDocument)
    # 6. From: 1
    # 7. To: 1
    # 8. Item: 0 (wdExportDocumentContent)
    # 9. IncludeDocProps: $true
    # 10. KeepIRM: $true
    # 11. CreateBookmarks: 1 (wdExportCreateHeadingBookmarks)
    # 12. DocStructureTags: $true
    # 13. BitmapMissingFonts: $true
    # 14. UseISO19005_1: $false
    $doc.ExportAsFixedFormat(
        $fullOutput,
        17,
        $false,
        0,
        0,
        1,
        1,
        0,
        $true,
        $true,
        1,
        $true,
        $true,
        $false
    )

    if (-not (Test-Path $fullOutput)) {
        throw "Output PDF was not generated by Microsoft Word"
    }

    $size = (Get-Item $fullOutput).Length
    Write-Output "CONVERSION_SUCCESS: $size"
} catch {
    Write-Error "CONVERSION_FAILED: $_"
    exit 1
} finally {
    if ($doc -ne $null) {
        try { $doc.Close([ref]$false) } catch {}
        try { [System.Runtime.InteropServices.Marshal]::ReleaseComObject($doc) | Out-Null } catch {}
    }
    if ($word -ne $null) {
        try { $word.Quit() } catch {}
        try { [System.Runtime.InteropServices.Marshal]::ReleaseComObject($word) | Out-Null } catch {}
    }
    [System.GC]::Collect()
    [System.GC]::WaitForPendingFinalizers()
}
